"""
RESUMO DIDÁTICO:
Este script demonstra o uso de operadores aritméticos aplicados a tipos de dados textuais 
(strings). No Python, o sinal de adição (+) é utilizado para a concatenação, unindo 
múltiplas strings em uma única sequência. Já o sinal de multiplicação (*) atua como um 
operador de repetição, permitindo replicar uma string por um determinado número de vezes 
inteiras. Essa versatilidade dos operadores permite manipular textos de forma rápida e 
eficiente sem a necessidade de laços de repetição manuais.
"""

concatencao = 'A' + 'B' + 'C'

print(concatencao)


a_dez_vezes = 'A' * 10

nome_quatro_vezes = 'Leo' * 4

print(a_dez_vezes)

print(nome_quatro_vezes)