"""
RESUMO DIDÁTICO:
Este script demonstra o funcionamento do tipo primitivo 'bool' (booleano) no Python. 
Através de operadores de comparação (==), o código avalia se determinadas expressões 
são verdadeiras (True) ou falsas (False). Além disso, utiliza a função type() para 
comprovar que tanto o resultado de uma comparação quanto as palavras-reservadas 
True e False pertencem à classe booleana, que é a base para estruturas de decisão 
em qualquer algoritmo.
"""

# bool = True or False

print(27 == 27)

print(27 == 32)

print(type(32 == 32))

print(type(True))

print(type(False))