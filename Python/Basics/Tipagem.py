"""
RESUMO DIDÁTICO:
Este script apresenta os tipos de dados primitivos fundamentais do Python: Inteiros 
(int), Números de Ponto Flutuante (float) e Cadeias de Caracteres (str). 
O Python é uma linguagem de tipagem dinâmica, o que significa que ele identifica 
automaticamente o tipo do dado baseado no valor atribuído. Enquanto os inteiros 
representam números positivos ou negativos sem casas decimais, os floats utilizam 
o ponto (padrão americano) para representar valores fracionários. Já as strings 
são delimitadas por aspas e representam qualquer tipo de texto ou sequência de 
símbolos, sendo essenciais para a comunicação entre o programa e o usuário.
"""

# Números inteiros (int)
# Podem ser positivos, negativos ou zero.
print(22)
print(-22)

# Números de ponto flutuante (float)
# Representam números com casas decimais.
print(2.7, -3.2)

# Cadeias de caracteres (str)
# Textos delimitados por aspas simples ou duplas.
print('Aboud')